// The dashboard's embedded city datasets currently own the records. Keep the backend
// snapshot aligned so Ask, hearings and email briefings see the same projects.
import {readFileSync,writeFileSync} from 'node:fs';
import vm from 'node:vm';
import {REGIONAL_DATA} from '../data/regional.js';
import '../public/housing-data.js';
const HOUSING_RECORDS=JSON.parse(readFileSync(new URL('../public/data/housing-records.json',import.meta.url)));
import {fileURLToPath} from 'node:url';
export function dashboardProjects(){
 const html=readFileSync(new URL('../public/index.html',import.meta.url),'utf8');
 const start=html.indexOf('const STAGES ='),end=html.indexOf("let currentCity = 'sunnyvale';");
 if(start<0||end<=start)throw new Error('Dashboard data boundaries changed; update the extractor.');
 const records=vm.runInNewContext(html.slice(start,end)+';Object.entries(CITIES).flatMap(([city,c])=>c.data.map(p=>({...p,city})))',{window:{REGIONAL_DATA,HOUSING_RECORDS},DashboardHousing:globalThis.DashboardHousing}, {timeout:5000});
 if(!Array.isArray(records)||!records.length||records.some(p=>!p.id||!p.city||!p.type))throw new Error('Invalid project dataset');
 return JSON.parse(JSON.stringify(records));
}
export function dashboardSources(){
 const html=readFileSync(new URL('../public/index.html',import.meta.url),'utf8');
 const start=html.indexOf('const OFFICIAL_LINKS ='),end=html.indexOf('let PROJECT_CITY = null;');
 if(start<0||end<=start)throw Error('Official source boundaries changed.');
 const links=vm.runInNewContext(html.slice(start,end)+';OFFICIAL_LINKS',{window:{REGIONAL_DATA}},{timeout:5000});
 const catalog=JSON.parse(readFileSync(new URL('../public/data/municipalities.json',import.meta.url)));
 const labels={...Object.fromEntries(catalog.cities.map(c=>[c.key,c.label])),...Object.fromEntries(Object.entries(REGIONAL_DATA.cities).map(([k,c])=>[k,c.label])),westsanjose:'West San Jose'};
 return Object.entries(links).flatMap(([key,items])=>items.map((r,i)=>({id:key+'-dashboard-'+i,city:labels[key],category:r.cat==='Planning Hub'?'Planning':r.cat==='Development Projects'?'Development':r.cat,title:r.title,url:r.url,note:r.note})));
}
if(process.argv[1]===fileURLToPath(import.meta.url)){
 const records=dashboardProjects();
 const baseRecords=records.filter(p=>!REGIONAL_DATA.cities[p.city]?.coverageId);
 const additional="\n// Added localities are loaded from the shared coverage files, without duplicating them here.\nimport {REGIONAL_CITIES as coverageCities} from './regional.js';\nconst projectIds=new Set(PROJECTS.map(p=>p.id));\nfor(const [city,c] of Object.entries(coverageCities))if(c.coverageId)for(const record of c.data)if(!projectIds.has(record.id)){PROJECTS.push({...record,city});projectIds.add(record.id);}\n";
 writeFileSync(new URL('../data/projects.js',import.meta.url),'// Generated by npm run sync:projects from the dashboard city records.\nexport const PROJECTS = '+JSON.stringify(baseRecords,null,2)+';\n'+additional);
 const sources=dashboardSources();
 writeFileSync(new URL('../data/official-sources.json',import.meta.url),JSON.stringify(sources,null,2)+'\n');
 console.log(`Synchronized ${records.length} project records and ${sources.length} official sources.`);
}
